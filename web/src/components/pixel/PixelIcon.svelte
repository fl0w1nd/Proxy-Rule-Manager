  interface IconData {
    dim: number;
    cells: Array<[number, number]>;
  }

  // Grids are static, so parse each icon once and reuse the rect list across
  // all instances; long lists may render a hundred icons at once.
  const cache = new Map<string, IconData>();

  function iconData(iconName: string, renderSize: number): IconData {
    const gridSource = renderSize < 16 && grids12[iconName] ? grids12 : grids;
    const cacheKey = `${iconName}:${gridSource === grids12 ? 12 : 16}`;
    let data = cache.get(cacheKey);
    if (!data) {
      const grid = gridSource[iconName] || grids[iconName] || grids['chevron-right'];
      const cols = Math.max(...grid.map((r) => r.length));
      const dim = Math.max(cols, grid.length, 1);
      const offsetX = Math.floor((dim - cols) / 2);
      const offsetY = Math.floor((dim - grid.length) / 2);
      const cells: Array<[number, number]> = [];
      grid.forEach((row, y) => {
        for (let x = 0; x < row.length; x++) {
          if (row[x] === '#') cells.push([x + offsetX, y + offsetY]);
        }
      });
      data = { dim, cells };
      cache.set(cacheKey, data);
    }
    return data;
  }

